    def ReadI2C(self,addr,base=0x00200000):
        self.WriteAXI(base+0x120,0x0f) # TX FIFO threshold
        self.WriteAXI(base+0x100,0x02) # reset TX FIFO
        self.WriteAXI(base+0x100,0x01) # enable I2C
        self.WriteAXI(base+0x108,0x1a8) # write TXFIFO, initiate i2c write to slave 1010100W, start
        self.WriteAXI(base+0x108,(addr>>8)&0xff) # high address byte
        self.WriteAXI(base+0x108,(addr>>0)&0xff) # low address byte
        self.WriteAXI(base+0x108,0x1a9) # write TXFIFO, initiate i2c read from slave 1010100R, repeated start
        self.WriteAXI(base+0x108,0x201) # read 2 bytes, stop
        d = self.ReadAXI(base+0x10c) # read RXFIFO
        return d

    def WriteI2C(self,addr,data,base=0x00200000):
        self.WriteAXI(base+0x120,0x0f) # TX FIFO threshold
        self.WriteAXI(base+0x100,0x02) # reset TX FIFO
        self.WriteAXI(base+0x100,0x01) # enable I2C
        self.WriteAXI(base+0x108,0x1a8) # write TXFIFO, initiate i2c write to slave 1010100W, start
        self.WriteAXI(base+0x108,(addr>>8)&0xff) # high address byte
        self.WriteAXI(base+0x108,(addr>>0)&0xff) # low address byte
        self.WriteAXI(base+0x108,0x200|((data>>0)&0xff)) # low data byte, stop
        while True:
            d = self.ReadAXI(base+0x020) # read status
            if (d&0xf)==0x4: # txfifo empty, i2c transaction complete
                return
            else:
                time.sleep(0.01)

